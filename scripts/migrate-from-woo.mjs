#!/usr/bin/env node
/**
 * Generates migrations/0002_seed.sql from the captured WooCommerce Store API
 * payloads in data/raw/.
 *
 * Run once; the output is committed so the import is reproducible and
 * reviewable rather than a one-off side effect against a live database.
 *
 *   node scripts/migrate-from-woo.mjs
 */

import { writeFileSync, mkdirSync, readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { loadRaw, buildCategories, buildBooks, sql } from './lib/catalogue.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'migrations', '0002_seed.sql');

// Written by scripts/fetch-images.mjs. Real dimensions let the pages reserve
// space for each cover, so the grid doesn't reflow as images load.
const DIMS_PATH = join(ROOT, 'data', 'image-dimensions.json');
const dims = existsSync(DIMS_PATH) ? JSON.parse(readFileSync(DIMS_PATH, 'utf8')) : {};
if (!Object.keys(dims).length) {
  console.warn('! data/image-dimensions.json missing - run scripts/fetch-images.mjs first.');
}

const { products, categories: rawCategories } = loadRaw();
const categories = buildCategories(rawCategories);
const books = buildBooks(products);

const lines = [];
const w = (s = '') => lines.push(s);

w('-- Seed: As-Subkī Books catalogue, imported from WooCommerce.');
w('-- GENERATED by scripts/migrate-from-woo.mjs - do not hand-edit.');
w(`-- ${books.length} books, ${categories.length} categories, ` +
  `${books.reduce((n, b) => n + b.images.length, 0)} images.`);
w();
w('PRAGMA foreign_keys = ON;');
w();

// -- Categories -------------------------------------------------------------
// Parents before children, or the foreign key fails on insert.
const byDepth = [...categories].sort(
  (a, b) => a.path.split('/').length - b.path.split('/').length || a.path.localeCompare(b.path),
);

w('-- Categories (WooCommerce ids retained).');
for (const [i, c] of byDepth.entries()) {
  w(
    `INSERT INTO categories (id, slug, name, parent_id, sort, path) VALUES ` +
      `(${c.id}, ${sql(c.slug)}, ${sql(c.name)}, ${c.parentId ?? 'NULL'}, ${i}, ${sql(c.path)});`,
  );
}
w();

// -- Books ------------------------------------------------------------------
// Explicit ids so book_categories and book_images can reference them without
// depending on insertion order or last_insert_rowid().
w('-- Books.');
for (const [i, b] of books.entries()) {
  const id = i + 1;
  w(
    `INSERT INTO books (id, slug, legacy_slug, legacy_wc_id, title, title_ar, ` +
      `description_html, price_pence, stock, reserved, status) VALUES (` +
      `${id}, ${sql(b.slug)}, ${sql(b.legacySlug)}, ${b.wcId}, ${sql(b.title)}, ` +
      `${sql(b.titleAr)}, ${sql(b.descriptionHtml)}, ${b.pricePence}, ${b.stock}, 0, 'live');`,
  );
}
w();

w('-- Book ↔ category.');
for (const [i, b] of books.entries()) {
  for (const catId of b.categoryIds) {
    w(`INSERT OR IGNORE INTO book_categories (book_id, category_id) VALUES (${i + 1}, ${catId});`);
  }
}
w();

w('-- Images. "books/" keys resolve to static assets under public/img/.');
for (const [i, b] of books.entries()) {
  for (const img of b.images) {
    const d = dims[img.key] ?? {};
    w(
      `INSERT INTO book_images (book_id, image_key, alt, sort, width, height) VALUES ` +
        `(${i + 1}, ${sql(img.key)}, ${sql(img.alt)}, ${img.sort}, ` +
        `${d.width ?? 'NULL'}, ${d.height ?? 'NULL'});`,
    );
  }
}
w();

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join('\n'), 'utf8');

// -- Report -----------------------------------------------------------------
const noImage = books.filter((b) => b.images.length === 0);
const noDesc = books.filter((b) => !b.descriptionHtml);
const uncategorised = books.filter((b) => b.categoryIds.includes(18) || b.categoryIds.length === 0);

console.log(`Wrote ${OUT}`);
console.log(`  ${books.length} books, ${categories.length} categories, ` +
            `${books.reduce((n, b) => n + b.images.length, 0)} images`);
console.log(`  in stock: ${books.filter((b) => b.stock > 0).length}, ` +
            `out: ${books.filter((b) => b.stock === 0).length}`);
console.log('\nOwner backlog to surface in the admin dashboard:');
console.log(`  ${noImage.length} books with no image`);
console.log(`  ${noDesc.length} books with no description`);
console.log(`  ${uncategorised.length} books uncategorised`);
